/** 按一年中的第几天取一句，每天不同 */
export function dailyQuote(now: Date = new Date()): Quote {
  const start = new Date(now.getFullYear(), 0, 0)
  const day = Math.floor((now.getTime() - start.getTime()) / 86400000)
  return QUOTES[day % QUOTES.length]
}
